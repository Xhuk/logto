<#
.SYNOPSIS

.DESCRIPTION
    La autoridad del contrato es `C:\proyectos\contracts\katra\_canonical.md`. Esa versión lleva
    integra y sí son datos nuestros.

    Este script produce la copia que se publica: quita los bloques marcados
    `<!-- internal:begin --> … <!-- internal:end -->`, deja un encabezado que dice de dónde viene, y
    falla si el resultado todavía contiene un identificador conocido.

    El endpoint es público a propósito: la guía se necesita **antes** de que exista la app, y pedir un
    token con `scope: all` para leer documentación sería sobre-privilegio. Lo que se cierra no es el
    conocimiento, son los identificadores.

.EXAMPLE
    .\scripts\sync-integration-guide.ps1 -Sync

.EXAMPLE
    .\scripts\sync-integration-guide.ps1 -Verify
#>
[CmdletBinding()]
param(
  [switch] $Sync,
  [switch] $Verify
)

$ErrorActionPreference = 'Stop'

$source = 'C:\proyectos\contracts\katra\_canonical.md'
$repo = git rev-parse --show-toplevel 2>$null
if (-not $repo) { throw 'No es un repositorio git.' }
$target = Join-Path $repo 'docs/katra/integration-guide.md'

if (-not (Test-Path $source)) { throw "No existe la fuente: $source" }

$forbidden = @(
  '3ni0yi', '2thyo9', 'g6qx2x', '94zk5v', '5lkfax', # tenants
  'crjxk9ds8d0ef0hmv15sp', 'r9jh2yvopv6gp2r9lyku9', '49tl064h4i3fhrxb8lshk', # app ids
  'C:\proyectos', 'Xhuk/', 'kv/projects/katra' # rutas e infra
)

function Build-PublicGuide {
  $lines = [System.IO.File]::ReadAllLines($source)
  $out = New-Object System.Collections.Generic.List[string]
  $insideInternal = $false

  foreach ($line in $lines) {
    if ($line -match '<!--\s*internal:begin\s*-->') { $insideInternal = $true; continue }
    if ($line -match '<!--\s*internal:end\s*-->') { $insideInternal = $false; continue }
    if (-not $insideInternal) { $out.Add($line) }
  }

  # ASCII only: Windows PowerShell may read this file as ANSI, and accents would land in the
  # published document as mojibake.
  $header = @(
    '<!-- Public copy. Generated by scripts/sync-integration-guide.ps1: do not edit by hand.  -->',
    '<!-- The authority of this contract lives in the IdP repository; this copy leaves out    -->',
    '<!-- the internal identifiers (tenants, applications, repo paths, evidence). It is       -->',
    '<!-- served at GET /api/katra/integration-guide.                                         -->',
    ''
  )

  return (($header + $out) -join "`n")
}

$rendered = Build-PublicGuide

foreach ($needle in $forbidden) {
  if ($rendered -match [regex]::Escape($needle)) {
    exit 1
  }
}

if ($Sync) {
  New-Item -ItemType Directory -Force -Path (Split-Path $target) | Out-Null
  [System.IO.File]::WriteAllText($target, $rendered, (New-Object System.Text.UTF8Encoding($false)))
  Write-Host "Generada: $target" -ForegroundColor Green
}

if ($Verify -or -not $Sync) {
  if (-not (Test-Path $target)) {
    Write-Host 'La guía publicada no existe. Corre -Sync.' -ForegroundColor Red
    exit 1
  }

  $current = [System.IO.File]::ReadAllText($target)
  if ($current -ne $rendered) {
    Write-Host 'La guía publicada NO coincide con lo que produce el contrato. Corre -Sync y commitea.' -ForegroundColor Red
    exit 1
  }

  Write-Host 'Guía publicada en sincronía con el contrato y sin identificadores internos.' -ForegroundColor Green
}
